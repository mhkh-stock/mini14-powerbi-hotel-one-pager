#!/usr/bin/env python3
"""Generate SAMPLE hotel data for Mini #14 (deterministic, seed 14).

Fictional Islamabad hotel "Margalla View Hotel": 40 rooms, 4 room
types, Jan–Jun 2026. Writes data/rooms.csv, data/bookings.csv,
data/payments.csv. Re-running reproduces the identical files.

Design: stayed bookings are generated by walking each room day by day
(a room can never be double-booked, so occupancy can never exceed
100%); cancelled / no-show bookings are added afterwards — they never
occupied a room. One payment row per booking: stayed -> paid,
cancelled -> refunded, no-show -> failed.
"""
import csv
import random
from datetime import date, timedelta
from pathlib import Path

SEED = 14
ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"

# room_type, rooms, base nightly rate (PKR), capacity (max guests)
ROOM_TYPES = [
    ("Standard", 18, 8000, 2),
    ("Deluxe", 12, 12000, 3),
    ("Executive Suite", 6, 20000, 2),
    ("Family Suite", 4, 16000, 4),
]

CHANNELS = ["OTA", "Direct", "Walk-in", "Travel Agent"]
CHANNEL_WEIGHTS = [40, 30, 15, 15]  # OTA leads, direct second

# Monthly booking-start probability per room-day: demand builds from
# the quiet winter (Jan) to the spring peak (May), then eases in Jun.
START_PROB = {1: 0.060, 2: 0.070, 3: 0.080, 4: 0.090, 5: 0.100, 6: 0.090}
# Stay-length weights (nights 1..5): average stay ~3 nights.
STAY_WEIGHTS = [15, 25, 30, 18, 12]

def _pick_weighted(rng, items, weights):
    total = sum(weights)
    x = rng.uniform(0, total)
    for item, w in zip(items, weights):
        x -= w
        if x <= 0:
            return item
    return items[-1]


def _rate(rng, base, checkin):
    # Weekend uplift (Fri/Sat check-ins pay ~10% more) + small noise,
    # rounded to the nearest PKR 100 so totals reconcile cleanly.
    uplift = 1.10 if checkin.weekday() in (4, 5) else 1.0
    return int(round(base * uplift * rng.uniform(0.95, 1.08) / 100.0)) * 100


def main():
    rng = random.Random(SEED)
    DATA.mkdir(parents=True, exist_ok=True)
    start = date(2026, 1, 1)
    end = date(2026, 6, 30)

    rooms = []
    prefix = {"Standard": "STD", "Deluxe": "DLX",
              "Executive Suite": "EXE", "Family Suite": "FAM"}
    floor = {"Standard": 1, "Deluxe": 2, "Executive Suite": 3, "Family Suite": 2}
    for rtype, count, base, cap in ROOM_TYPES:
        for i in range(count):
            rooms.append({
                "room_id": f"{prefix[rtype]}-{floor[rtype]}{i + 1:02d}",
                "room_type": rtype,
                "nightly_rate_pkr": base,
                "floor": floor[rtype],
                "capacity": cap,
            })
    room_by_type = {}
    for r in rooms:
        room_by_type.setdefault(r["room_type"], []).append(r)
    base_rate = {r["room_type"]: r["nightly_rate_pkr"] for r in rooms}
    capacity = {r["room_type"]: r["capacity"] for r in rooms}

    bookings = []
    bid = [0]

    def _new_booking(room, checkin, nights, status, cancel_date=""):
        bid[0] += 1
        rtype = room["room_type"]
        rate = _rate(rng, base_rate[rtype], checkin)
        lead = rng.randrange(1, 46)
        booking_date = checkin - timedelta(days=lead)
        bookings.append({
            "booking_id": f"B{bid[0]:04d}",
            "room_id": room["room_id"],
            "booking_date": booking_date.isoformat(),
            "checkin_date": checkin.isoformat(),
            "checkout_date": (checkin + timedelta(days=nights)).isoformat(),
            "nights": nights,
            "room_type": rtype,
            "channel": _pick_weighted(rng, CHANNELS, CHANNEL_WEIGHTS),
            "guests": rng.randint(1, capacity[rtype]),
            "nightly_rate_pkr": rate,
            "total_pkr": rate * nights,
            "status": status,
            "cancel_date": cancel_date,
        })

    # Stayed bookings: walk each room day by day, never double-book.
    for room in rooms:
        day = start
        while day <= end:
            if rng.random() < START_PROB[day.month]:
                nights = _pick_weighted(rng, [1, 2, 3, 4, 5], STAY_WEIGHTS)
                if day + timedelta(days=nights) > date(2026, 7, 4):
                    nights = max(1, (date(2026, 7, 4) - day).days)
                _new_booking(room, day, nights, "stayed")
                day += timedelta(days=nights)
            else:
                day += timedelta(days=1)

    stayed = [b for b in bookings if b["status"] == "stayed"]

    # Cancelled bookings (~85): reserved, then cancelled 1–7 days
    # before check-in. They never occupied a room.
    for _ in range(85):
        rtype = _pick_weighted(
            rng, [t[0] for t in ROOM_TYPES],
            [t[1] for t in ROOM_TYPES])
        room = rng.choice(room_by_type[rtype])
        checkin = start + timedelta(days=rng.randrange(0, 181))
        nights = _pick_weighted(rng, [1, 2, 3, 4], [25, 35, 25, 15])
        cancel = checkin - timedelta(days=rng.randrange(1, 8))
        _new_booking(room, checkin, nights, "cancelled",
                     cancel_date=cancel.isoformat())

    # No-show bookings (~25): the guest never arrived; the charge failed.
    for _ in range(25):
        rtype = _pick_weighted(
            rng, [t[0] for t in ROOM_TYPES],
            [t[1] for t in ROOM_TYPES])
        room = rng.choice(room_by_type[rtype])
        checkin = start + timedelta(days=rng.randrange(0, 181))
        nights = _pick_weighted(rng, [1, 2, 3], [40, 40, 20])
        _new_booking(room, checkin, nights, "no-show")

    # One payment per booking: stayed -> paid, cancelled -> refunded,
    # no-show -> failed (the charge never went through).
    payments = []
    for i, b in enumerate(bookings, start=1):
        if b["status"] == "stayed":
            status, paid_on = "paid", b["checkin_date"]
        elif b["status"] == "cancelled":
            status, paid_on = "refunded", b["cancel_date"]
        else:
            status, paid_on = "failed", ""
        payments.append({
            "payment_id": f"PAY-{i:04d}",
            "booking_id": b["booking_id"],
            "amount_pkr": b["total_pkr"],
            "status": status,
            "paid_on": paid_on,
        })

    for name, rows, fields in [
        ("rooms.csv", rooms, ["room_id", "room_type", "nightly_rate_pkr",
                              "floor", "capacity"]),
        ("bookings.csv", bookings,
         ["booking_id", "room_id", "booking_date", "checkin_date",
          "checkout_date", "nights", "room_type", "channel", "guests",
          "nightly_rate_pkr", "total_pkr", "status", "cancel_date"]),
        ("payments.csv", payments,
         ["payment_id", "booking_id", "amount_pkr", "status", "paid_on"]),
    ]:
        with open(DATA / name, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=fields)
            w.writeheader()
            w.writerows(rows)

    n_stayed = sum(1 for b in bookings if b["status"] == "stayed")
    n_cx = sum(1 for b in bookings if b["status"] == "cancelled")
    n_ns = sum(1 for b in bookings if b["status"] == "no-show")
    room_nights = sum(b["nights"] for b in bookings if b["status"] == "stayed")
    revenue = sum(p["amount_pkr"] for p in payments if p["status"] == "paid")
    print(f"rooms: {len(rooms)}")
    print(f"bookings: {len(bookings)} (stayed {n_stayed}, "
          f"cancelled {n_cx}, no-show {n_ns})")
    print(f"room-nights sold: {room_nights} / {40 * 181} available "
          f"({room_nights / (40 * 181) * 100:.1f}% occupancy)")
    print(f"payments: {len(payments)} (paid "
          f"{sum(1 for p in payments if p['status'] == 'paid')}, refunded "
          f"{sum(1 for p in payments if p['status'] == 'refunded')}, failed "
          f"{sum(1 for p in payments if p['status'] == 'failed')})")
    print(f"paid revenue: PKR {revenue:,}")


if __name__ == "__main__":
    main()
